import assert from 'node:assert/strict';
import { cleanUrl, sha256 } from '../src/utils/toolbox.ts';
import { validateShortenUrl, requestShortLink, handleShorten } from '../api/_shorten.js';
import { useWindowManagerStore } from '../src/store/windowManagerStore.ts';

assert.equal(cleanUrl('https://example.com/a?utm_source=x&item=2&fbclid=abc#part'), 'https://example.com/a?item=2#part');
assert.throws(() => cleanUrl('javascript:alert(1)'));
assert.throws(() => cleanUrl('https://name:secret@example.com'));
assert.equal(await sha256('abc'), 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
assert.throws(() => validateShortenUrl('http://127.0.0.1/private'));
assert.throws(() => validateShortenUrl('file:///secret'));
let requests = 0;
const destination = 'https://example.com/?a=1&b=2';
const mock = async (url, options) => { requests++; assert.equal(url,'https://is.gd/create.php'); assert.equal(options.body.get('url'),destination); return {ok:true,json:async()=>({shorturl:'https://is.gd/example'})}; };
assert.equal(await requestShortLink(destination,mock),'https://is.gd/example');
await requestShortLink(destination,mock);
assert.equal(requests,1);
await assert.rejects(requestShortLink('https://example.com/failure',async()=>({ok:true,json:async()=>({errorcode:3})})));
const res={statusCode:0,setHeader(){},end(body){this.body=JSON.parse(body);}};
await handleShorten({method:'GET',headers:{}},res);
assert.equal(res.statusCode,405);
await handleShorten({method:'POST',headers:{},body:{url:'javascript:alert(1)'}},res);
assert.equal(res.statusCode,400);

globalThis.window = {innerWidth:1280,innerHeight:800};
const store = useWindowManagerStore.getState();
store.openWindow({id:'test-project',title:'Test',type:'workcard',status:'open',position:{x:100,y:50},size:{width:800,height:600},meta:{description:'Full project content'}});
store.maximizeWindow('test-project');
assert.equal(useWindowManagerStore.getState().windows['test-project'].status,'maximized');
assert.equal(useWindowManagerStore.getState().windows['test-project'].meta.description,'Full project content');
store.minimizeWindow('test-project');
store.restoreWindow('test-project');
assert.equal(useWindowManagerStore.getState().windows['test-project'].status, 'maximized');
store.unmaximizeWindow('test-project');
assert.deepEqual(useWindowManagerStore.getState().windows['test-project'].size,{width:800,height:600});
store.closeWindow('test-project');
console.log('Tool checks passed: URL handling, checksums, Unicode inspection, file signatures, shortener validation/cache/errors, and project maximize/restore. No live short links created.');

const { inspectFile, inspectUnicode } = await import('../src/utils/inspectors.ts');
assert.match(inspectUnicode('pay\u200bpal\u202e'), /U\+200B/);
assert.match(inspectUnicode('pay\u200bpal\u202e'), /direction control/);
assert.match(inspectUnicode('p\u0430ypal'), /Mixed scripts/);
assert.match(inspectUnicode('hello'), /No checked invisible/);
assert.throws(() => inspectUnicode(''));
assert.match(inspectFile(Uint8Array.from([0xff,0xd8,0xff]), 'photo.jpg', 100, ''), /Consistent/);
assert.match(inspectFile(Uint8Array.from([0x4d,0x5a]), 'photo.jpg', 100, 'image/jpeg'), /Extension differs/);
assert.match(inspectFile(new Uint8Array(), 'empty', 0, ''), /Unknown/);
assert.match(inspectFile(Uint8Array.from([0x50,0x4b,3,4]), 'report.docx', 100, ''), /Consistent/);
console.log('New inspector regression checks passed.');
